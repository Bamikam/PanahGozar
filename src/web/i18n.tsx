const DICTS: Record<Lang, Record<string, string>> = { en, fa };

export interface I18nCtx {
  lang: Lang;
  dir: "ltr" | "rtl";
  t: (key: string, vars?: Record<string, string | number>) => string;
  setLang: (l: Lang, options?: { user?: boolean }) => void;
  formatDate: (value: string | null | undefined, withTime?: boolean) => string;
  formatNumber: (value: number | string) => string;
}

const Ctx = createContext<I18nCtx>({
  lang: "en",
  dir: "ltr",
  t: (k) => k,
  setLang: () => {},
  formatDate: () => "",
  formatNumber: (v) => String(v),
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const stored = localStorage.getItem("pg.lang");
      if (stored === "en" || stored === "fa") return stored;
    } catch {
      // storage unavailable
    }
    return "en";
  });

  const dir = lang === "fa" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    try {
      localStorage.setItem("pg.lang", lang);
    } catch {
      // ignore
    }
  }, [lang, dir]);

  const setLang = useCallback((next: Lang, options?: { user?: boolean }) => {
    try {
      if (options?.user !== false) localStorage.setItem("pg.lang.user", "1");
    } catch {
      // ignore
    }
    setLangState(next);
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let value = DICTS[lang][key] ?? DICTS.en[key] ?? key;
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          value = value.replaceAll(`{${name}}`, String(replacement));
        }
      }
      return value;
    },
    [lang]
  );

  const formatDate = useCallback(
    (value: string | null | undefined, withTime = true) => {
      if (!value) return DICTS[lang]["common.never"] ?? "Never";
      const date = new Date(value);
      if (Number.isNaN(date.getTime())) return "—";
      try {
        return new Intl.DateTimeFormat(lang === "fa" ? "fa-IR" : "en-US", {
          dateStyle: "medium",
          ...(withTime ? { timeStyle: "short" } : {}),
        }).format(date);
      } catch {
        return date.toISOString();
      }
    },
    [lang]
  );

  const formatNumber = useCallback(
    (value: number | string) => {
      const num = typeof value === "string" ? Number(value) : value;
      if (!Number.isFinite(num)) return String(value);
      try {
        return new Intl.NumberFormat(lang === "fa" ? "fa-IR" : "en-US").format(num);
      } catch {
        return String(num);
      }
    },
    [lang]
  );

  const value = useMemo<I18nCtx>(
    () => ({ lang, dir, t, setLang, formatDate, formatNumber }),
    [lang, dir, t, setLang, formatDate, formatNumber]
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  return useContext(Ctx);
}
